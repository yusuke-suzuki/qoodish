export type EmojiCategoryId = (typeof EMOJI_CATEGORIES)[number]['id'];

export function emojiCategoryOf(emoji: string | null): EmojiCategoryId | null {
  if (emoji === null) {
    return null;
  }

  const category = EMOJI_CATEGORIES.find((candidate) =>
    (candidate.emoji as readonly string[]).includes(emoji)
  );

  return category?.id ?? null;
}
